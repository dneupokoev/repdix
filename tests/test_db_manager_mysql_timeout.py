"""Тесты формирования init_command для MySQL/MariaDB в DBManager.

Проверяем Проблему 1: серверный таймаут (MAX_EXECUTION_TIME / max_statement_time)
должен попадать в init_command пула даже при readonly=true.
"""

from __future__ import annotations

dv_file_version = '261030.02'

import asyncio
import logging
from pathlib import Path
from unittest.mock import AsyncMock, patch

import yaml
from pymysql.constants import CLIENT

from app.core.db_manager import DBManager


def _base_conf(**overrides) -> dict:
    """Минимальный валидный конфиг MySQL-БД для тестов."""
    conf = {
        "type": "mysql",
        "host": "localhost",
        "port": 3306,
        "user": "tester",
        "password": "secret",
        "database": "testdb",
        "readonly": True,
        "is_mariadb": False,
    }
    conf.update(overrides)
    return conf


def _make_manager(tmp_path: Path, db_conf: dict) -> DBManager:
    """Создаёт DBManager с временным databases.yaml."""
    config_path = tmp_path / "databases.yaml"
    config_path.write_text(
        yaml.safe_dump({"databases": {"main_db": db_conf}}, allow_unicode=True),
        encoding="utf-8",
    )
    return DBManager(config_path=str(config_path))


def _create_pool_kwargs(tmp_path: Path, db_conf: dict):
    """Подключается к БД с замоканным aiomysql.create_pool.

    Returns:
        (kwargs вызова create_pool, экземпляр DBManager).
    """
    manager = _make_manager(tmp_path, db_conf)
    fake_pool = object()
    with patch(
        "app.core.db_manager.aiomysql.create_pool",
        new=AsyncMock(return_value=fake_pool),
    ) as mocked:
        asyncio.run(manager.connect("main_db"))

    assert mocked.call_count == 1, "create_pool должен вызываться ровно один раз"
    return mocked.call_args.kwargs, manager


def test_mysql_readonly_sets_transaction_read_only_and_timeout(tmp_path: Path) -> None:
    """readonly=true, не MariaDB: в init_command есть и readonly, и таймаут."""
    kwargs, manager = _create_pool_kwargs(tmp_path, _base_conf())

    init_cmd = kwargs["init_command"]
    expected_ms = manager.query_timeout * 1000

    assert init_cmd is not None
    assert "transaction_read_only = 1" in init_cmd
    assert f"MAX_EXECUTION_TIME = {expected_ms}" in init_cmd
    assert kwargs["client_flag"] == CLIENT.MULTI_STATEMENTS


def test_mysql_readwrite_sets_timeout_only(tmp_path: Path) -> None:
    """readonly=false, не MariaDB: ставится только MAX_EXECUTION_TIME."""
    kwargs, manager = _create_pool_kwargs(tmp_path, _base_conf(readonly=False))

    init_cmd = kwargs["init_command"]
    expected_ms = manager.query_timeout * 1000

    assert init_cmd is not None
    assert "transaction_read_only" not in init_cmd
    assert f"MAX_EXECUTION_TIME = {expected_ms}" in init_cmd


def test_mariadb_readonly_uses_max_statement_time(tmp_path: Path) -> None:
    """MariaDB: используется max_statement_time (секунды), а не MAX_EXECUTION_TIME."""
    kwargs, manager = _create_pool_kwargs(
        tmp_path, _base_conf(is_mariadb=True),
    )

    init_cmd = kwargs["init_command"]

    assert init_cmd is not None
    assert "transaction_read_only = 1" in init_cmd
    assert f"max_statement_time = {manager.query_timeout}" in init_cmd
    assert "MAX_EXECUTION_TIME" not in init_cmd
    # Ожидание блокировок ограничивается и для MariaDB: эти SET не требуют
    # прав на запись, поэтому ставятся даже при readonly=true.
    assert (
        f"SET SESSION innodb_lock_wait_timeout = {manager.lock_wait_timeout}"
        in init_cmd
    )
    assert (
        f"SET SESSION lock_wait_timeout = {manager.lock_wait_timeout}"
        in init_cmd
    )


def test_custom_init_statements_are_used(tmp_path: Path) -> None:
    """init_statements из конфига имеют приоритет и склеиваются через '; '."""
    statements = [
        "SET SESSION MAX_EXECUTION_TIME = 15000",
        "SET SESSION sql_mode = 'STRICT_TRANS_TABLES'",
    ]
    kwargs, _ = _create_pool_kwargs(
        tmp_path, _base_conf(init_statements=statements),
    )

    assert kwargs["init_command"] == "; ".join(statements)
    assert kwargs["client_flag"] == CLIENT.MULTI_STATEMENTS


def test_invalid_init_statements_fall_back_to_autogenerated(tmp_path: Path) -> None:
    """init_statements не список — игнорируется, генерируются SET по умолчанию."""
    kwargs, manager = _create_pool_kwargs(
        tmp_path, _base_conf(init_statements="SET SESSION x = 1"),
    )

    init_cmd = kwargs["init_command"]

    assert init_cmd is not None
    assert f"MAX_EXECUTION_TIME = {manager.query_timeout * 1000}" in init_cmd


def test_mysql_sets_lock_wait_timeouts_default(
    tmp_path: Path, monkeypatch,
) -> None:
    """По умолчанию (LOCK_WAIT_TIMEOUT не задан) ставится 5 секунд."""
    # pipenv подгружает .env, поэтому переменную надо именно удалить.
    monkeypatch.delenv("LOCK_WAIT_TIMEOUT", raising=False)
    kwargs, manager = _create_pool_kwargs(tmp_path, _base_conf())

    init_cmd = kwargs["init_command"]

    assert manager.lock_wait_timeout == 5
    assert init_cmd is not None
    assert "SET SESSION innodb_lock_wait_timeout = 5" in init_cmd
    assert "SET SESSION lock_wait_timeout = 5" in init_cmd


def test_lock_wait_timeout_from_env(tmp_path: Path, monkeypatch) -> None:
    """LOCK_WAIT_TIMEOUT=10 из окружения попадает в оба SET SESSION."""
    monkeypatch.setenv("LOCK_WAIT_TIMEOUT", "10")
    kwargs, manager = _create_pool_kwargs(tmp_path, _base_conf())

    init_cmd = kwargs["init_command"]

    assert manager.lock_wait_timeout == 10
    assert init_cmd is not None
    assert "SET SESSION innodb_lock_wait_timeout = 10" in init_cmd
    assert "SET SESSION lock_wait_timeout = 10" in init_cmd


def _make_manager_for_db(
    tmp_path: Path, db_name: str, db_conf: dict,
) -> DBManager:
    """Создаёт DBManager с временным databases.yaml и одной БД."""
    config_path = tmp_path / "databases.yaml"
    config_path.write_text(
        yaml.safe_dump({"databases": {db_name: db_conf}}, allow_unicode=True),
        encoding="utf-8",
    )
    return DBManager(config_path=str(config_path))


def _connect_with_mocked_pool(manager: DBManager, db_name: str) -> None:
    """Вызывает manager.connect() с замоканным aiomysql.create_pool."""
    with patch(
        "app.core.db_manager.aiomysql.create_pool",
        new=AsyncMock(return_value=object()),
    ):
        asyncio.run(manager.connect(db_name))


def _warning_messages(caplog) -> list[str]:
    """Возвращает текст всех WARNING-записей из caplog."""
    return [
        record.getMessage()
        for record in caplog.records
        if record.levelno == logging.WARNING
    ]


def test_init_statements_warns_on_semicolon(tmp_path: Path, caplog) -> None:
    """';' вне строковых литералов в init_statements логирует WARNING.

    Проверяем именно ';' между стейтментами: внутри кавычек '_strip_string_literals'
    его вырезает, и предупреждение намеренно не срабатывает.
    """
    caplog.set_level(logging.WARNING, logger="app.core.db_manager")

    db_conf = _base_conf(
        init_statements=[
            "SET SESSION sql_mode = 'STRICT_TRANS_TABLES'; SET SESSION a = 1",
        ],
    )
    manager = _make_manager_for_db(tmp_path, "db", db_conf)

    _connect_with_mocked_pool(manager, "db")

    warnings = _warning_messages(caplog)
    assert any("init_statements содержит ';'" in msg for msg in warnings), (
        f"ожидалось предупреждение про ';', получено: {warnings}"
    )


def test_init_statements_no_warning_without_semicolon(
    tmp_path: Path, caplog,
) -> None:
    """Без ';' в init_statements WARNING про ';' не логируется."""
    caplog.set_level(logging.WARNING, logger="app.core.db_manager")

    db_conf = _base_conf(
        init_statements=["SET SESSION a = 1", "SET SESSION b = 2"],
    )
    manager = _make_manager_for_db(tmp_path, "db", db_conf)

    _connect_with_mocked_pool(manager, "db")

    warnings = _warning_messages(caplog)
    assert not any(
        "init_statements содержит ';'" in msg for msg in warnings
    ), f"не ожидалось предупреждение про ';', получено: {warnings}"
